#pragma once
// ============================================================================
// MbaaMemTrace — 実機のゲームメモリを毎フレーム記録する
//
// 【何のためか】
//   harness の FakeGame は机上で決めたタイムラインで動いており、実機の
//   振る舞いと一致している保証がない。実際、フレーム進行のずれは
//   FakeGame では再現しなかった（実機テストで初めて露見した）。
//   実機の値を測ってテスト環境に反映するために、生の推移を記録する。
//
// 【seam の外に置く】
//   IGameMemory は同期ロジックが使う最小の窓口で、観測用の値を足すと
//   本来の責務がぼやける。トレースはゲーム固有の観測なので直接アドレスを読む。
//   DLL 内でのみ動き、harness ではリンクしない。
//
// 【デシンク指標】
//   RNG 状態とキャラのシーケンス番号は、状態が分岐すると即座に食い違う。
//   体力やタイマーより早く、かつ確実に差が出る。
//
// 【有効化】
//   環境変数 CCCASTER_MEM_TRACE=1。毎フレーム1行出るため通常プレイでは無効。
// ============================================================================

#include <cstdint>

namespace cccaster::game_memory {

class MbaaMemTrace {
  public:
    /// 環境変数で有効化されているか（プロセス起動時に1回だけ判定）
    static bool IsEnabled();

    /// 1フレーム分を記録する。SceneRunner::Step() の末尾から毎フレーム呼ぶ。
    /// @param netFrame 同期側のフレーム番号（writeHead）。両者の突き合わせ軸になる。
    static void Sample(uint32_t netFrame);
};

} // namespace cccaster::game_memory
