#pragma once
// ============================================================================
// GamePhase — 格闘ゲームネット対戦で同期が必要なゲームフェーズ定義
//
// 【設計思想】
//   格闘ゲーム共通の概念としてのフェーズ定義。
//   「キャラ選択→ロード→対戦→リマッチ」はどの格闘ゲームにも存在する遷移。
//   具体的なフェーズ検出（メモリ読み取り等）はゲーム固有層が担う。
// ============================================================================

namespace cccaster::game_interface {

/**
 * @brief ネットワーク対戦で同期が必要なゲームの主要なフェーズ
 *
 * @details
 *   各フェーズで同期処理（入力遅延、ロールバック、スキップ）が異なるため、
 *   シーンマネージャが参照する判定基準となる。
 */
enum class GamePhase {
    Unknown,     ///< 不明な状態（初期化前、遷移中など）
    MainMenu,    ///< メインメニュー
    CharaSelect, ///< キャラクター選択画面
    Loading,     ///< ロード中
    InGame,      ///< 対戦中
    Rematch      ///< リマッチ画面
};

} // namespace cccaster::game_interface
