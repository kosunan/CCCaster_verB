namespace cccaster::game_interface::native_hud {
// GAUGE04のROUND/STAGE画像と同じ9pxの字面・16pxの画像枠。
// D/E/Aの画素を基に、LとYを同じ直立した線幅で構成する。
// 字形だけを定数化し、黒縁と透過画像は初期化時に作る。
inline std::array<uint32_t,48*16> RoundDelayPixels() {
    std::array<uint8_t,48*16> ink{};
    constexpr uint8_t d[9][8]{
        {51,187,187,187,187,119,17,0},
        {68,255,255,255,255,255,204,0},
        {68,255,255,0,34,238,255,85},
        {68,255,255,0,0,187,255,119},
        {68,255,255,0,0,187,255,119},
        {68,255,255,0,0,187,255,119},
        {68,255,255,0,0,221,255,119},
        {68,255,255,187,221,255,238,34},
        {68,255,255,255,255,170,68,0},
    };
    for(unsigned r=0;r<9;++r)for(unsigned c=0;c<8;++c)ink[(r+4)*48+c+3]=d[r][c];
    constexpr uint8_t e[9][7]{
        {187,187,187,187,187,187,102},
        {255,255,255,255,255,255,119},
        {255,255,68,0,0,0,0},
        {255,255,153,119,119,34,0},
        {255,255,255,255,255,68,0},
        {255,255,119,68,68,17,0},
        {255,255,68,0,0,0,0},
        {255,255,204,187,187,187,187},
        {255,255,255,255,255,255,255},
    };
    for(unsigned r=0;r<9;++r)for(unsigned c=0;c<7;++c)ink[(r+4)*48+c+12]=e[r][c];
    constexpr uint8_t l[9][7]{
        {187,187,51,0,0,0,0},
        {255,255,255,0,0,0,0},
        {255,255,68,0,0,0,0},
        {255,255,153,0,0,0,0},
        {255,255,255,0,0,0,0},
        {255,255,119,0,0,0,0},
        {255,255,68,0,0,0,0},
        {255,255,204,187,187,187,187},
        {255,255,255,255,255,255,255},
    };
    for(unsigned r=0;r<9;++r)for(unsigned c=0;c<7;++c)ink[(r+4)*48+c+20]=l[r][c];
    constexpr uint8_t a[9][9]{
        {0,0,34,187,187,119,0,0,0},
        {0,0,119,255,255,221,0,0,0},
        {0,0,187,255,153,255,51,0,0},
        {0,17,255,187,85,255,136,0,0},
        {0,102,255,119,17,255,204,0,0},
        {0,170,255,119,68,204,255,34,0},
        {0,238,255,255,255,255,255,119,0},
        {85,255,187,68,68,102,255,204,0},
        {136,255,119,0,0,0,238,255,17},
    };
    for(unsigned r=0;r<9;++r)for(unsigned c=0;c<9;++c)ink[(r+4)*48+c+27]=a[r][c];
    constexpr uint8_t y[9][7]{
        {187,187,0,0,0,187,187},
        {255,255,17,0,17,255,255},
        {85,255,136,0,136,255,85},
        {0,221,238,68,238,221,0},
        {0,68,255,255,255,68,0},
        {0,0,119,255,119,0,0},
        {0,0,119,255,119,0,0},
        {0,0,119,255,119,0,0},
        {0,0,119,255,119,0,0},
    };
    for(unsigned r=0;r<9;++r)for(unsigned c=0;c<7;++c)ink[(r+4)*48+c+38]=y[r][c];
    std::array<uint32_t,48*16> pixels{};
    for(int y=0;y<16;++y)for(int x=0;x<48;++x) {
        if(!ink[y*48+x])continue;
        for(int dy=-2;dy<=2;++dy)for(int dx=-2;dx<=2;++dx) {
            if((dx==-2 || dx==2) && (dy==-2 || dy==2))continue;
            if(x+dx>=0 && x+dx<48 && y+dy>=0 && y+dy<16)pixels[(y+dy)*48+x+dx]=0xff000000;
        }
    }
    for(unsigned i=0;i<ink.size();++i)if(ink[i])pixels[i]=0xff000000u|uint32_t(ink[i])*0x010101u;
    return pixels;
}
}
