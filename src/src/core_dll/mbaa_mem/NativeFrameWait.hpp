#pragma once
#include "shared_contracts/CheckedPatch.hpp"

namespace cccaster::game_memory::native_frame_wait {
// Carnival140。Sleepの引数生成と時計の反復だけを飛ばす。
// 動画状態確認、経過値、基準時刻更新、通信不足時のreturn 0を残す。
inline constexpr uintptr_t SleepSite = 0x41fdfb, LoopSite = 0x42007e;
inline constexpr uint8_t SleepOriginal[] = {
    0x85,0xc0,0x74,0x04,0x6a,0x08,0xeb,0x02,0x6a,0x02,0xff,0x15,0xd0,0xb1,0x51,0x00,
    0xd9,0x45,0x08,0x51,0x8d,0x7c,0x24,0x0c,0xd9,0x1c,0x24,0x8b,0xc6,
    0xe8,0x93,0x00,0x00,0x00};
inline constexpr uint8_t SleepJump[] = {0xeb,0x0e}; // 0x41fe0b
inline constexpr uint8_t LoopOriginal[] = {0x0f,0x85,0xd3,0x00,0x00,0x00};
inline constexpr uint8_t LoopJump[] = {0xe9,0xd4,0x00,0x00,0x00,0x90}; // 0x420157
inline constexpr uint8_t Gate[] = {
    0x55,0x8b,0xec,0x83,0xe4,0xf8,0x83,0xec,0x20,0x83,0x7e,0x4c,0x01,
    0x53,0x57,0x75,0x0a,0x33,0xc0,0x5f,0x5b,0x8b,0xe5,0x5d,0xc2,0x04,0x00};
// 既存のVシンク分岐先を再利用する。FPUを解放し、本体通信を必要時に1回処理する。
// 描画エンジンのVシンク設定そのものは変更しない。
inline constexpr uint8_t Continue[] = {
    0x8b,0x0d,0x6c,0xd3,0x54,0x00,0xdd,0xd8,0x3b,0x0d,0xd0,0xd1,0x55,0x00,
    0x75,0x05,0xe8,0x24,0x09,0x07,0x00,0x5f,0xb8,0x01,0x00,0x00,0x00,
    0x5b,0x8b,0xe5,0x5d,0xc2,0x04,0x00};

// 呼出側がゲーム入口停止中、またはこの関数群の外にいるゲームスレッドであること。
template<class Memory> patch::Result Apply(Memory& memory) {
    struct Guard { uintptr_t address; std::span<const uint8_t> bytes; };
    for (const auto& guard : {Guard{0x41ffd0, Gate}, Guard{0x420157, Continue}}) {
        std::array<uint8_t, 64> actual{};
        if (!memory.Read(guard.address, actual.data(), guard.bytes.size()))
            return {patch::Error::Read, memory.LastError(), guard.address, "frame_wait_context"};
        if (std::memcmp(actual.data(), guard.bytes.data(), guard.bytes.size()))
            return {patch::Error::Mismatch, 0, guard.address, "frame_wait_context"};
    }
    const patch::Spec specs[]{
        {"frame_wait_sleep", SleepSite, SleepOriginal, SleepJump},
        {"frame_wait_loop", LoopSite, LoopOriginal, LoopJump}};
    return patch::Apply(memory, specs);
}

patch::Result Enable();
} // namespace cccaster::game_memory::native_frame_wait
