#pragma once
// ============================================================================
// LogSink — ログ行のバッファリングとバックグラウンド書き出し
//
// 【何のためか】
//   従来の HookLog は 1 行ごとに fopen/fprintf/fclose を排他なしで実行して
//   いた。これを叩くのは通信スレッド（受信パケットごと）とゲームスレッド
//   （SceneRunner::Step / MbaaMemTrace は毎フレーム）の 2 系統で、
//     (a) 行が混線して読めない
//     (b) 同期ファイル I/O がフレームタイミングを汚染し、計測値そのものが
//         信用できなくなる
//   という二重の実害が出ていた。同期改修は計測を土台にするので、まずここを
//   潰す。
//
// 【方針】
//   - ファイルハンドルは開きっぱなし。close は Shutdown() のみ。
//   - 書き手（ゲームスレッド／通信スレッド）はロック下でキューに push する
//     だけで返る。I/O の完了は待たない。
//   - 実際の write/fflush は専用スレッドが行う。1 行 push ごとに起こすので
//     通常の欠損窓は 1ms 未満。負荷が高いときはワーカーが I/O している間に
//     溜まった分が次の 1 回でまとめて書かれ、自然にバッチ化する。
//   - [FATAL] / [ASSERT] を含む行は呼び出しスレッドで同期フラッシュする。
//     直後にクラッシュしても残す必要があるため、ここだけは待つ。
//
// 【Win32 非依存】
//   一部モジュールを Linux でもビルドする予定があるため、実装は標準 C++
//   （<mutex> / <thread> / <condition_variable> / <cstdio>）だけで書く。
//   CRITICAL_SECTION 等の Win32 専用 API と windows.h には依存しない。
//   出力先パスの解決だけは Win32 依存なので、呼び出し側（dllmain.cpp）が
//   SetLogPath() で外から渡す。
// ============================================================================

#include <string>

namespace cccaster::core::log {

/// 出力先ファイルパスを設定する。ファイルを開く前の 1 回だけ有効。
/// 未設定ならカレントディレクトリの "cccaster_hook_log.txt" にフォールバックする。
void SetLogPath(const std::string &path);

/// バックグラウンド書き出しスレッドを起動する。
/// ★ DllMain の中（ローダーロック下）から呼んではいけない。
///   起動前の WriteLine() は呼び出しスレッドでの同期書き出しになる
///   （初期化フェーズは行数が少なく、むしろ落ちたときに残る方が価値が高い）。
void StartWriter();

/// 1 行書く。ワーカー起動後は積んで即座に返り、I/O の完了は待たない。
/// 末尾の改行は不要（付けて出力する）。
void WriteLine(const char *msg);

/// 呼び出しスレッドで溜まっている行を書き切る。
void FlushNow();

/// 書き切ってファイルを閉じる。以降の WriteLine() は捨てられる。
/// @param blocking false ならロック取得を諦めて途中で切り上げる。
///                 プロセス終了（DllMain の lpReserved != nullptr）では
///                 他スレッドがロックを持ったまま消えている可能性があるため、
///                 必ず false で呼ぶこと。
void Shutdown(bool blocking);

} // namespace cccaster::core::log
