// DataPaths — 設定ファイルの置き場所を1箇所で決める
//
// 【なぜ存在するか】
//   設定ファイルのパスは配置フォルダー名を含む**相対パス**で
//   書かれていた。DLL はゲームプロセス（MBAA.exe）の中で動くため、これは
//   ゲームのカレントディレクトリ基準になる。ゲーム側が `SetCurrentDirectory` を
//   呼べば、書き手と読み手が別の場所を指しうる。しかもその食い違いは
//   「設定が効かない」という形でしか現れず、原因が見えない。
//
//   `HookLog` は既に「DLL 自身のパスから解決する」方式に直してあった
//   （`dllmain.cpp` の `GetModuleFileNameA`）。同じことを設定ファイルにもする。
//
// 【ルート】
//   DLL が置かれているディレクトリ。実機では `<ゲーム>\cccaster_B\` にあたり、
//   フォルダー名をコードへ重複して埋め込まず、DLLと同じ場所を指す。
//
// 【ルート未設定のとき】
//   harness や単体テストでは DLL が無いのでルートは設定されない。その場合は
//   渡された名前をそのまま返す（＝従来どおりカレントディレクトリ基準）。
// ============================================================================

#include <string>

namespace cccaster::core::paths {

/// データディレクトリを設定する。dllmain の初期化で1回だけ呼ぶ。
/// 末尾の区切り文字は有無どちらでもよい。
void SetDataRoot(const std::string &absoluteDir);

/// ファイル名をデータディレクトリ基準の絶対パスに解決する。
/// ルート未設定なら fileName をそのまま返す。
std::string Resolve(const std::string &fileName);

/// 現在のデータディレクトリ（未設定なら空文字）。ログ用。
std::string GetDataRoot();

} // namespace cccaster::core::paths
